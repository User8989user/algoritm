""" Слияние двух отсортированных массивов (без дополнительных аллокаций)
Дано два отсортированных массива.
Первый массив имеет размер результирующего массива, а его конец заполнен нулями.
Объединить массивы необходимо без создания третьего массива.
Аналог задачи: Merge Sorted Array 
Что нужно сделать:
Напишите функцию, которая объединяет массивы, заполняя первый массив с конца.
 Поясните, почему заполнение с конца позволяет избежать перезаписи данных."""


def merge_sorted_inplace(nums1, m, nums2, n):
    # Указатели на последние реальные элементы
    p1 = m - 1
    p2 = n - 1
    p = m + n - 1  # позиция для записи в nums1

    while p1 >= 0 and p2 >= 0:
        if nums1[p1] > nums2[p2]:
            nums1[p] = nums1[p1]
            p1 -= 1
        else:
            nums1[p] = nums2[p2]
            p2 -= 1
        p -= 1

    # Если остались элементы в nums2, копируем их (nums1 уже на месте)
    while p2 >= 0:
        nums1[p] = nums2[p2]
        p2 -= 1
        p -= 1

# Пример
nums1 = [1, 2, 3, 0, 0, 0]
m = 3
nums2 = [2, 5, 6]
n = 3
merge_sorted_inplace(nums1, m, nums2, n)
print(nums1)  # [1, 2, 2, 3, 5, 6]

"""
Почему заполнение с конца безопасно?
Все элементы, которые могут быть перезаписаны, 
уже либо обработаны, либо находятся правее текущей позиции записи. 
Таким образом, мы не теряем данные."""
