from collections import deque

# класс TreeNode для представления узла дерева 
class TreeNode:
    def __init__(self, val=0, left=None, right=None):
        self.val = val
        self.left = left
        self.right = right

""" 1 Восстановление бинарного дерева из массива
Дан массив, представляющий бинарное дерево 
(например, в виде уровнями — level-order).
Необходимо восстановить структуру бинарного дерева.
Что нужно сделать:
Реализуйте функцию, которая строит дерево по переданному массиву. 
Объясните, как определяется связь родитель–потомок 
и какая структура данных используется для хранения узлов. """


def build_tree_from_level_order(arr):
    """
    Строит бинарное дерево из массива level‑order.
    :param arr: list, элементы могут быть None (отсутствие узла)
    :return: TreeNode — корень дерева
    """
    if not arr or arr[0] is None:
        return None

    root = TreeNode(arr[0])
    queue = deque([root])
    i = 1
    while queue and i < len(arr):
        node = queue.popleft()

        # Левый потомок
        if i < len(arr) and arr[i] is not None:
            node.left = TreeNode(arr[i])
            queue.append(node.left)
        i += 1

        # Правый потомок
        if i < len(arr) and arr[i] is not None:
            node.right = TreeNode(arr[i])
            queue.append(node.right)
        i += 1

    return root

"""
Объяснение:
Связь родитель–потомок определяется индексами в массиве: для узла
 с индексом i левый потомок — 2*i+1, правый — 2*i+2. 
 Мы строим дерево, обрабатывая узлы в порядке уровня, 
 чтобы корректно восстановить все связи.
 Хранение осуществляется в объектах TreeNode, связанных ссылками.
"""


""" 2 Симметричное бинарное дерево
Дано бинарное дерево.
Необходимо определить, является ли оно симметричным относительно своей середины.
Что нужно сделать:
Реализуйте рекурсивную или итеративную проверку зеркальности левого и правого поддеревьев.
 Поясните, какие пары узлов сравниваются и почему алгоритм работает корректно. """

def is_symmetric(root):
    """
    Проверяет, является ли дерево симметричным.
    :param root: TreeNode
    :return: bool
    """
    def is_mirror(t1, t2):
        if not t1 and not t2:
            return True
        if not t1 or not t2:
            return False
        return (t1.val == t2.val and
                is_mirror(t1.left, t2.right) and
                is_mirror(t1.right, t2.left))

    return is_mirror(root, root) if root else True

""" Объяснение:
Алгоритм сравнивает узлы, которые должны быть зеркальными относительно центральной оси.
 Рекурсивно проверяются пары (left.left, right.right) и (left.right, right.left). 
 Условие остановки — оба узла None (зеркально) или один None (не зеркально).
 Работает корректно, так как зеркальность определяется именно такими парами. """

"""  3 Поиск минимальной глубины бинарного дерева
Дано бинарное дерево.
Необходимо найти его минимальную глубину (расстояние от корня до ближайшего листа).
Что нужно сделать:
Реализуйте решение с использованием BFS или DFS. 
Объясните, почему поиск в ширину (BFS) позволяет корректно найти минимальную глубину. """

def min_depth_bfs(root):
    """
    Возвращает минимальную глубину дерева с помощью BFS.
    :param root: TreeNode
    :return: int
    """
    if not root:
        return 0

    queue = deque([(root, 1)])  # (узел, текущая глубина)
    while queue:
        node, depth = queue.popleft()
        if not node.left and not node.right:
            return depth
        if node.left:
            queue.append((node.left, depth + 1))
        if node.right:
            queue.append((node.right, depth + 1))
    return 0

""" Объяснение:
BFS исследует узлы уровень за уровнем. 
Первый лист, найденный на некоторой глубине, гарантированно является ближайшим к корню,
 так как все предыдущие уровни были проверены и не содержали листьев. 
Это делает BFS эффективным для этой задачи.
 """


""" 4 Поиск произведения максимального и минимального элементов
Дано бинарное дерево поиска (BST), представленное в виде массива.
Необходимо найти произведение минимального и максимального значений.
Что нужно сделать:
Восстановите BST (если требуется) и найдите минимальный и максимальный элементы, используя свойства BST.
 Поясните, почему поиск крайних элементов выполняется за O(h), где h — высота дерева. """


def product_min_max_bst(arr):
    """
    Восстанавливает BST из массива level‑order и возвращает произведение минимального и максимального значений.
    :param arr: list
    :return: int
    """
    root = build_tree_from_level_order(arr)  # функция из задачи 1
    if not root:
        return 0

    # Поиск минимального (левый край)
    min_node = root
    while min_node.left:
        min_node = min_node.left

    # Поиск максимального (правый край)
    max_node = root
    while max_node.right:
        max_node = max_node.right

    return min_node.val * max_node.val

""" Объяснение:
Свойство BST: все значения в левом поддереве меньше корня, в правом — больше.
 Поэтому минимальный элемент находится в самой левой ветви, максимальный — в самой правой.
  Поиск требует O(h) сравнений, так как на каждом шаге переходим к одному потомку.
 Произведение вычисляется просто. """


""" 5 Сравнение двух бинарных деревьев
Даны два бинарных дерева.
Необходимо определить, являются ли они идентичными (по структуре и значениям узлов).
Что нужно сделать:
Реализуйте рекурсивную проверку соответствия узлов обоих деревьев. 
Объясните, какие условия должны выполняться, чтобы деревья считались одинаковыми. """


def is_same_tree(p, q):
    """
    Проверяет, идентичны ли два бинарных дерева.
    :param p: TreeNode
    :param q: TreeNode
    :return: bool
    """
    if not p and not q:
        return True
    if not p or not q:
        return False
    return (p.val == q.val and
            is_same_tree(p.left, q.left) and
            is_same_tree(p.right, q.right))

""" 
Объяснение:
Рекурсивный подход естественен для деревьев. 
Базовые случаи: оба пусты — одинаковы; один пуст — различаются. 
Затем сравниваются значения корней, и рекурсивно проверяются левые и правые поддеревья. 
Алгоритм корректен, так как охватывает все узлы в одинаковом порядке. """
