""" Сумма двух элементов массива
Дан неотсортированный массив целых чисел и число target.
Необходимо найти два элемента массива, сумма которых равна target.
Каждый элемент можно использовать только один раз.
Если подходящей пары нет — вернуть пустой массив.
Что нужно сделать:
Реализуйте эффективное решение за O(n), используя хеш-таблицу (словарь). 
Поясните, как хранение уже просмотренных элементов позволяет избежать двойного цикла. """


def two_sum(nums: list[int], target: int) -> list[int]:
    seen = {}
    for i, num in enumerate(nums):
        complement = target - num
        if complement in seen:
            return [seen[complement], i]
        seen[num] = i
    return []


""" 
Объяснение:
Хранение просмотренных элементов в словаре позволяет за O(1) проверить,
 было ли уже число, дополняющее текущее до target. 
Это позволяет избежать вложенного цикла. Сложность O(n) по времени и O(n) по памяти. """